"""Decision-log digest (task 0.19): parse `docs/decisions/log.md` and render
`docs/decisions/digest.md` (human and risk: high lead decisions, one line each, plus a
hand-picked "Standing rules" list). Scope: 0.19 lead answer 6, see `in_digest`.

Pure functions, no I/O: `board.py digest` reads the files and writes the output.

Log entries are `### <heading>` blocks. An entry's body runs to the next `### ` heading or
`---` separator line, whichever comes first (the real log has some blocks holding two entries
with no `---` between them, so both count as boundaries).

- risk: the last `risk: <level>` in the heading (usually a trailing `· risk: <level>`), else the
  first body line that *starts* with `risk: <level>` (bare or `- `-prefixed). None if neither.
- supersedes: an optional body line `Supersedes: <exact earlier heading>` (bare or bulleted).
  The digest then marks that earlier entry "(superseded by <this heading>)".

Standing rules come from `docs/decisions/standing-rules.md`, one bullet per rule:
`- <rule text> (cites: <exact heading, or its date · title>)`. The script never invents a rule; it only
refuses a bullet whose citation isn't an in-digest heading in the log.
"""
import re

# Twin of closeout.py's `decision_entries`/`split_log` split (on `### ` headings and `---`
# lines), duplicated on purpose so the two scripts don't import each other (0.19 lead answer 1).
# If a third user appears, extract a shared helper.
_HEADING = re.compile(r"^###[ \t]+(.*?)[ \t]*$")
_SEPARATOR = re.compile(r"^-{3,}[ \t]*$")
_BAD_HEADING = re.compile(r"^###(?=[^\s#])")
_HEADING_RISK = re.compile(r"\brisk:[ \t]*([a-z]+)", re.I)
_BODY_RISK = re.compile(r"^[ \t]*(?:[-*][ \t]+)?risk:[ \t]*([a-z]+)", re.I)
_SUPERSEDES = re.compile(r"^[ \t]*(?:[-*][ \t]+)?Supersedes:[ \t]*(.*?)[ \t]*$")
_RULE = re.compile(r"^-[ \t]+(.*)$")
_CITES = " (cites: "

TITLE = "# Decision digest"
INTRO = ("Generated by `python3 .claude/skills/board/board.py digest` from `docs/decisions/log.md` "
         "and `docs/decisions/standing-rules.md`. Do not edit by hand. The full log stays the source "
         "of truth; read it for the why.")
SCOPE = ("Every decision the human made (any risk), and every risk: high decision by the lead "
         "that is not a routine `<id> merge:` entry. One line each: date and title, who and risk, "
         "and the first sentence of its `Decided:` line. Newest first.")


def _norm(text):
    return " ".join((text or "").split())


def _heading_text(text):
    """A heading as written in a `Supersedes:`/`cites:` line: normalized, `### ` optional."""
    return _norm(re.sub(r"^#{3}[ \t]*", "", _norm(text)))


def parse_log_entries(text):
    """[{heading, risk, body, supersedes}] for every `### ` entry in the log, in file order.

    Raises ValueError for a malformed log: a heading before the first `---` (an entry with no
    closing separator), a risk: high heading missing its space after `###` (it would be silently
    dropped), a risk: high entry with an empty body, or a `Supersedes:` naming no logged heading.
    """
    lines = (text or "").splitlines()
    entries, current, seen_separator = [], None, False

    def close():
        if current is None:
            return
        body = "\n".join(current["lines"]).strip("\n")
        risk = current["risk"]
        supersedes = None
        for line in current["lines"]:
            if risk is None:
                m = _BODY_RISK.match(line)
                if m:
                    risk = m.group(1).lower()
            m = _SUPERSEDES.match(line)
            if m and supersedes is None:
                supersedes = _heading_text(m.group(1))
        if risk == "high" and not body.strip():
            raise ValueError(f"malformed log: risk: high entry has an empty body: {current['heading']}")
        entries.append({"heading": current["heading"], "risk": risk, "body": body,
                        "supersedes": supersedes})

    for line in lines:
        if _BAD_HEADING.match(line) and _HEADING_RISK.search(line):
            raise ValueError(f"malformed log: heading needs a space after '###': {line.strip()}")
        m = _HEADING.match(line)
        if m:
            close()
            heading = _norm(m.group(1))
            if not seen_separator:
                raise ValueError(f"malformed log: heading has no closing --- before it "
                                 f"(entries go after the header's ---): {heading}")
            risks = _HEADING_RISK.findall(heading)
            current = {"heading": heading, "risk": risks[-1].lower() if risks else None, "lines": []}
        elif _SEPARATOR.match(line):
            close()
            current, seen_separator = None, True
        elif current is not None:
            current["lines"].append(line)
    close()

    headings = {e["heading"] for e in entries}
    for e in entries:
        if e["supersedes"] is not None and e["supersedes"] not in headings:
            raise ValueError(f"Supersedes line in '{e['heading']}' names no logged heading: "
                             f"{e['supersedes']}")
    return entries


def parse_standing_rules(text):
    """[(rule_text, cited_heading)] from `standing-rules.md` bullets; other lines are ignored.
    Raises ValueError for a bullet with no `(cites: <heading>)`."""
    rules = []
    for line in (text or "").splitlines():
        m = _RULE.match(line)
        if not m:
            continue
        item = m.group(1).rstrip()
        rule, sep, cite = item.partition(_CITES)
        if not sep or not item.endswith(")") or not rule.strip() or not cite[:-1].strip():
            raise ValueError(f"standing rule must end with '(cites: <risk: high heading>)': {item}")
        rules.append((_norm(rule), _heading_text(cite[:-1])))
    return rules


SUMMARY_MAX = 220
# The first role named after "decided by" is the decider ("planner, accepted by team lead" is
# the planner's). "team lead", "the team lead" and "the lead" are the lead; "the human" is the
# human. Fix round 1: this used to take one word, so "team lead" parsed as "team" and dropped.
_WHO = re.compile(r"\bdecided by[ \t]+(?:the[ \t]+)?((?:team[ \t]+)?lead\b|[a-z-]+)", re.I)
_WHO_ALIASES = {"you": "human", "human": "human", "lead": "lead", "team lead": "lead",
                # Claude ran the team as lead before the agent roles existed (16-17 Oct 2026).
                "claude": "lead"}
# Every who the real log uses; RealRepo pins that no "decided by" heading falls outside this.
KNOWN_WHO = frozenset({"human", "lead", "tdd-guide", "builder", "planner", "plan",
                       "build-error-resolver", "pedagogy-author", "eval-author", "safety-reviewer",
                       "security-reviewer", "silent-failure-hunter", "reviewers"})
_DECIDED = re.compile(r"^[ \t]*(?:[-*][ \t]+)?\**Decided\**:\**[ \t]*(.*)$", re.I)
_BULLET = re.compile(r"^[ \t]*[-*][ \t]+(.*)$")
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9`\"'(\[])")
_ROUTINE_MERGE = re.compile(r"^[0-9][\w.]*[ \t]+merge:", re.I)
_DATE = re.compile(r"^(\d{1,2}) ([A-Z][a-z]{2}) (\d{4})$")
_MONTHS = {m: i for i, m in enumerate(
    ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"], 1)}


def decided_by(entry):
    """'human' (decided by you/human), 'lead' (lead, team lead, Claude), the first other role
    named, or None when the heading has no `decided by`."""
    m = _WHO.search(entry["heading"])
    if not m:
        return None
    who = " ".join(m.group(1).lower().split())
    return _WHO_ALIASES.get(who, who)


def digest_key(heading):
    """`<date> · <title>`: the heading without its `decided by ...` and `risk: ...` parts
    (so no who-clause, and no name in brackets after it, is copied into the digest)."""
    keep = []
    for part in (p.strip() for p in _norm(heading).split(" · ")):
        if part.lower().startswith("decided by"):
            break
        if not part.lower().startswith("risk:"):
            keep.append(part)
    return " · ".join(keep) or _norm(heading)


def _title(heading):
    parts = digest_key(heading).split(" · ", 1)
    return parts[1] if len(parts) == 2 and _DATE.match(parts[0]) else parts[-1]


def in_digest(entry):
    """Lead answer 6 (0.19): (a) every human decision, at any risk; (b) risk: high lead
    decisions that are not a routine `<id> merge:` entry. Builder, tdd-guide, planner and team
    entries stay out."""
    who = decided_by(entry)
    if who == "human":
        return True
    return (who == "lead" and entry["risk"] == "high"
            and not _ROUTINE_MERGE.match(_title(entry["heading"])))


_ABBREV = re.compile(r"(?:\be\.g|\bi\.e|\betc|\bvs)\.$", re.I)
_REVIEWER = re.compile(r"\b(reviewed_?by(?::|[ \t]+is[ \t]+set[ \t]+to)[ \t]*)([A-Za-z0-9][\w-]*)", re.I)
_REPO_URL = re.compile(r"\b(?:https?://)?github\.com/[\w-]+(?:/[\w-]+(?:\.[\w-]+)*)?")


def _redact(text):
    """No reviewer handle or repo owner is copied from the log (the repo is public)."""
    text = _REVIEWER.sub(lambda m: m.group(0) if m.group(2).lower() == "pending"
                         else m.group(1) + "<human>", text)
    return _REPO_URL.sub("GitHub", text)


def _first_sentence(text):
    text = _redact(_norm(text.replace("**", "")))
    first = text
    for m in _SENTENCE_END.finditer(text):
        if not _ABBREV.search(text[:m.start()]):
            first = text[:m.start()]
            break
    if len(first) > SUMMARY_MAX:
        first = first[:SUMMARY_MAX - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return first


def summary(entry):
    """First sentence of the entry's `Decided:` line, else of its first bullet, else ''."""
    lines = (entry.get("body") or "").splitlines()
    for i, line in enumerate(lines):
        m = _DECIDED.match(line)
        if m:
            if m.group(1).strip():
                text = [m.group(1)]
                for nxt in lines[i + 1:]:  # join the line's indented wrapped continuation
                    if not nxt.strip() or not nxt[:1].isspace() or _BULLET.match(nxt):
                        break
                    text.append(nxt)
                return _first_sentence(" ".join(text))
            for nxt in lines[i + 1:]:  # `- Decided:` with its text on the following lines
                if nxt.strip():
                    b = _BULLET.match(nxt)
                    return _first_sentence(b.group(1) if b else nxt)
    for line in lines:
        m = _BULLET.match(line)
        if m and m.group(1).strip():
            return _first_sentence(m.group(1))
    return ""


def _date_rank(heading):
    m = _DATE.match(digest_key(heading).split(" · ", 1)[0])
    if not m or m.group(2) not in _MONTHS:
        return 0  # undated sorts last
    return int(m.group(3)) * 10000 + _MONTHS[m.group(2)] * 100 + int(m.group(1))


def digest_entries(entries):
    """In-scope entries, exact duplicates dropped, newest date first (log order within a date)."""
    out, seen = [], set()
    for e in entries:
        ident = (e["heading"], e["body"])
        if in_digest(e) and ident not in seen:
            seen.add(ident)
            out.append(e)
    return sorted(out, key=lambda e: -_date_rank(e["heading"]))


def _superseded_by(entries):
    out = {}
    for e in entries:  # newest first: the first (newest) superseder wins
        if e["supersedes"] is not None:
            out.setdefault(e["supersedes"], e["heading"])
    return out


def _line(entry, replaced):
    tag = f"{decided_by(entry)}, risk: {entry['risk'] or 'none'}"
    if entry["heading"] in replaced:
        tag += f"; superseded by {digest_key(replaced[entry['heading']])}"
    text = summary(entry)
    return f"- {digest_key(entry['heading'])} ({tag})" + (f": {text}" if text else "")


def render_digest(entries, rules=()):
    """The text of `docs/decisions/digest.md`. Raises ValueError (render nothing) when a
    standing rule cites a heading that isn't an in-digest entry (full heading or date · title)."""
    kept = digest_entries(entries)
    citable = {e["heading"] for e in kept} | {digest_key(e["heading"]) for e in kept}
    for rule, cite in rules:
        if cite not in citable:
            raise ValueError(f"standing rule cites something that is not a digest heading "
                             f"(a human, or risk: high lead, decision in the log): {cite} "
                             f"(rule: {rule})")
    replaced = _superseded_by(entries)
    out = [TITLE, "", INTRO, "", "## Standing rules", ""]
    out += [f"- {rule}{_CITES}{cite})" for rule, cite in rules] or ["None yet."]
    out += ["", "## Decisions", "", SCOPE, ""]
    out += [_line(e, replaced) for e in kept] or ["None yet."]
    return "\n".join(out) + "\n"


def is_missing(entries, digest_text):
    """Headings of in-digest entries with no `- <date · title> (` line in `digest_text`."""
    lines = [l.rstrip() for l in (digest_text or "").splitlines()]
    missing = []
    for e in entries:
        if not in_digest(e) or e["heading"] in missing:
            continue
        prefix = f"- {digest_key(e['heading'])} ("
        if not any(l.startswith(prefix) for l in lines):
            missing.append(e["heading"])
    return missing
